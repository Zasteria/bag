#!/usr/bin/env python3
"""Turn the EU5 game data into the script this mod evaluates at runtime.

The question the mod answers is "what should I build in this province" — so the
generated layer is organised per building type, and the runtime scores exactly
one province at a time.

Emits, from `<EU5>/game/in_game/common`:

  scripted_triggers/wtp_generated_rgo_triggers.txt   is this raw material in the province
  scripted_triggers/wtp_generated_availability.txt   is this building worth offering
  script_values/wtp_generated_method_values.txt      what one method scores in a province
  scripted_effects/wtp_generated_buildings.txt       the candidates and their methods
  scripted_effects/wtp_generated_rows.txt            the row writers for all four lists
  localization/*/wtp_generated_l_*.yml               method names and recipes

The bonus formula is in eu5data.py, verified against the game's own tooltips.
A method's score is linear in its inputs, so it lands in script as a sum of
`if` clauses over the province's raw materials, divided by the method's total
input weight:

    wtp_bonus_weapon_smith_maintenance = {
        value = 0
        if = { limit = { wtp_province_has_lumber = yes } add = 0.2521 }
        if = { limit = { wtp_province_has_coal = yes }   add = 0.3034 }
        divide = 1.0605
        multiply = 10
    }

A building is worth what its best method is worth in that province, so the
runtime walks a building's methods and keeps the best — which is also what the
community spreadsheet this mod is modelled on does.

Usage:
    python3 mods/where_to_produce/tools/generate.py [<EU5>/game/in_game/common [<CMF>/in_game/common/scripted_effects]]

Both default to `reference/` — the game files, and whichever folder there holds
Community Mod Framework — so the arguments are only for pointing it at another
copy. Without CMF it cannot check that every CMM macro is called with arguments
CMF actually declares, which is the check that catches a silently swallowed
effect.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from eu5data import RGO_MAX_BONUS, Game, Method, load_game, load_dir, scalar  # noqa: E402

MOD_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(MOD_ROOT.parent.parent / "tools"))
import refs  # noqa: E402  the reference tree, resolved by mod id

OUT = MOD_ROOT / "in_game" / "common"
TRIGGERS_OUT = OUT / "scripted_triggers" / "wtp_generated_rgo_triggers.txt"
AVAIL_OUT = OUT / "scripted_triggers" / "wtp_generated_availability.txt"
VALUES_OUT = OUT / "script_values" / "wtp_generated_method_values.txt"
BUILDINGS_OUT = OUT / "scripted_effects" / "wtp_generated_buildings.txt"
ROWS_OUT = OUT / "scripted_effects" / "wtp_generated_rows.txt"
LOC_LANGUAGES = ("english", "russian")

# Written by the good-first design this one replaced.
RETIRED = (
    OUT / "script_values" / "wtp_generated_goods_values.txt",
    OUT / "script_values" / "wtp_generated_dispatch.txt",
    OUT / "script_values" / "wtp_generated_selected.txt",
    OUT / "script_values" / "wtp_generated_scoring.txt",
    OUT / "scripted_effects" / "wtp_generated_catalogue.txt",
    OUT / "scripted_effects" / "wtp_generated_menu.txt",
)

BOM = "﻿"
HEADER = "# GENERATED by mods/where_to_produce/tools/generate.py -- do not edit by hand."

# How tall each list can grow. Every list is registered at the height it needs
# and the row writers below are emitted up to these.
LISTS = (("regions", 20), ("areas", 20), ("provinces", 20), ("top", 12))

# Buildings staffed by burghers are the town half of the answer; everything else
# — labourers, peasants, slaves, clergy — is the rural half. That is the split
# the spreadsheet uses, and it matters because the two are built in different
# kinds of location.
TOWN_POPS = {"burghers"}


def amount(value: float) -> str:
    """An input amount the way the building panel shows it."""
    return ("%.2f" % value).rstrip("0").rstrip(".") or "0"


def method_id(method: Method, shared: set[str]) -> str:
    """A script-safe name, qualified by building only where a key is reused."""
    if method.key in shared:
        return "%s__%s" % (method.building, method.key)
    return method.key


def resolve_ids(game: Game) -> dict[tuple[str, str], str]:
    """Map every (building, method) to a unique identifier."""
    bodies: dict[str, set[tuple]] = {}
    for m in game.methods:
        bodies.setdefault(m.key, set()).add((m.output, tuple(sorted(m.inputs.items()))))
    ambiguous = {key for key, seen in bodies.items() if len(seen) > 1}
    return {(m.building, m.key): method_id(m, ambiguous) for m in game.methods}


def scored_methods(game: Game) -> list[Method]:
    """Methods that could take a raw material bonus at all."""
    return [m for m in game.methods
            if m.raw_inputs(game.raw_goods) and m.total_input]


def buildings_with_methods(game: Game, ids) -> dict[str, list[tuple[str, Method]]]:
    """Every building we can say something about, and the methods behind it."""
    out: dict[str, list[tuple[str, Method]]] = {}
    for method in sorted(scored_methods(game), key=lambda m: (m.building, -m.output, m.key)):
        rows = out.setdefault(method.building, [])
        name = ids[(method.building, method.key)]
        if name not in {n for n, _ in rows}:
            rows.append((name, method))
    return out


def brace_match(text: str, open_at: int) -> str:
    depth = 0
    for i in range(open_at, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_at:i + 1]
    return "{}"


def country_gates(building_dir: Path) -> dict[str, str]:
    """Each building's `country_potential`, verbatim, keyed by building.

    Taken as raw text rather than round tripped through the parser: it is an
    ordinary country scoped trigger and the game's own wording is the only
    version guaranteed to mean what the game means.
    """
    gates: dict[str, str] = {}
    for path in sorted(building_dir.glob("*.txt")):
        if "readme" in path.name.lower():
            continue
        text = path.read_text(encoding="utf-8-sig", errors="replace")
        for top in re.finditer(r"^(\w+) = \{", text, re.M):
            body = brace_match(text, top.end() - 1)
            gate = re.search(r"^\tcountry_potential = \{", body, re.M)
            if gate:
                inner = brace_match(body, gate.end() - 1)[1:-1]
                lines = [ln.strip() for ln in inner.splitlines() if ln.strip()]
                if lines:
                    gates[top.group(1)] = "\n".join("\t" + ln for ln in lines)
    return gates


def render_triggers(goods: list[str]) -> str:
    out = [BOM + HEADER, "#",
           "# True when some location in this province works that raw material.",
           "# The bonus is province wide, which is what the game's own tooltip reports.",
           "# Scope: province", ""]
    for good in goods:
        out += ["wtp_province_has_%s = {" % good,
                "\tany_location_in_province = {",
                "\t\traw_material = goods:%s" % good,
                "\t}", "}", ""]
    return "\n".join(out)


def render_values(game: Game, ids) -> str:
    out = [BOM + HEADER, "#",
           "# Per production method, in one province: the raw material bonus it would",
           "# get and the volume it would turn out at that bonus. Every input counts",
           "# towards the divisor, produced goods included -- that is why a ceiling can",
           "# sit well below %g%%." % RGO_MAX_BONUS,
           "#",
           "# Efficiency multiplies output, so volume is what makes two different",
           "# buildings comparable: a mill at half its ceiling still turns out more",
           "# than a village workshop running at the full bonus.",
           "# Scope: province", ""]

    emitted: set[str] = set()
    for method in sorted(scored_methods(game),
                         key=lambda m: (m.produced, -m.output, m.building, m.key)):
        name = ids[(method.building, method.key)]
        if name in emitted:
            continue
        emitted.add(name)
        ceiling = method.ceiling(game.raw_goods)
        out.append("# %s in %s -- produces %s, output %g, ceiling %.2f%%" % (
            method.key, method.building, method.produced, method.output, ceiling))
        out.append("wtp_bonus_%s = {" % name)
        out.append("\tvalue = 0")
        for good, value in sorted(method.raw_inputs(game.raw_goods).items()):
            out.append("\tif = { limit = { wtp_province_has_%s = yes } add = %s }"
                       % (good, format(value, "g")))
        out.append("\tdivide = %s" % format(method.total_input, "g"))
        out.append("\tmultiply = %g" % RGO_MAX_BONUS)
        out.append("}")
        out.append("wtp_volume_%s = {" % name)
        out.append("\tvalue = wtp_bonus_%s" % name)
        out.append("\tdivide = 100")
        out.append("\tadd = 1")
        out.append("\tmultiply = %s" % format(method.output, "g"))
        out.append("}")
        out.append("")
    return "\n".join(out)


def render_availability(game: Game, ids, gates, buildings, entries) -> str:
    """Whether a building is worth putting in front of this country.

    Three things make one worthless, and all three are in the game files:

      * it carries a `country_potential` this country fails — a Japanese clan
        reform, an English tag, or a flat `always = no`;
      * it is special or foreign, so it is not built in the ordinary way;
      * nowhere in the realm works any raw material it could take a bonus from,
        which is the only thing this mod has to say about it.

    Alongside goes the town/rural gate, so one trigger answers "should this row
    exist" and the runtime never has to know a building's pop type.
    """
    out = [BOM + HEADER, "#",
           "# Whether a building is worth offering. Reads the realm's raw materials",
           "# from the globals wtp_scan_realm_materials leaves behind, and carries the",
           "# building's own country_potential verbatim where it has one.",
           "# Scope: country", ""]

    for building in sorted(buildings):
        rows = buildings[building]
        raw = sorted({g for _, m in rows for g in m.raw_inputs(game.raw_goods)})
        info = entries[building]
        special = (scalar(info, "is_special") == "yes"
                   or scalar(info, "is_foreign") == "yes")
        gate = gates.get(building)

        out.append("wtp_building_available_%s = {" % building)
        if special:
            out.append("\t# special or foreign: not built the ordinary way")
            out.append("\talways = no")
        else:
            out.append("\tOR = {")
            for good in raw:
                out.append("\t\thas_global_variable = wtp_realm_has_%s" % good)
            out.append("\t}")
            if gate is not None:
                out.append("\t# country_potential of %s, verbatim" % building)
                out.append(gate)
        out.append("}")

        # Whether the country has it *now*. `can_build_building` is the engine's
        # own answer, so it moves with advances and ages without this mod knowing
        # anything about them, and `building_type_is_obsolete` drops the ones a
        # successor has replaced. Kept apart from the availability trigger above
        # because they answer different questions -- "never" against "not yet" --
        # and the menu offers them as two toggles.
        out.append("wtp_building_unlocked_%s = {" % building)
        out.append("\tcan_build_building = building_type:%s" % building)
        out.append("\tNOT = { building_type_is_obsolete = building_type:%s }" % building)
        out.append("}")

        town = scalar(info, "pop_type") in TOWN_POPS
        out.append("# %s is staffed by %s" % (building, scalar(info, "pop_type")))
        out.append("wtp_building_in_scope_%s = {" % building)
        out.append("\tOR = {")
        out.append("\t\tNOT = { has_global_variable = wtp_half }")
        out.append("\t\tglobal_var:wtp_half = 1")
        out.append("\t\tglobal_var:wtp_half = %d" % (2 if town else 3))
        out.append("\t}")
        out.append("}")
        out.append("")
    return "\n".join(out)


def render_buildings(game: Game, ids, buildings, used_goods) -> tuple[str, str]:
    """The candidates, their methods, and the two lookups the rows need."""
    out = [BOM + HEADER, "#", "# Scope: country", ""]
    loc = ["l_english:"]

    out += ["# Which raw materials the realm works anywhere. One pass answers it for",
            "# every building at once, and wtp_building_available_<b> reads the globals",
            "# it leaves. Scope: any",
            "wtp_forget_realm_materials = {"]
    for good in used_goods:
        out.append("\tif = { limit = { has_global_variable = wtp_realm_has_%s }"
                   " remove_global_variable = wtp_realm_has_%s }" % (good, good))
    out += ["}", "", "# Scope: location", "wtp_note_realm_material = {"]
    for index, good in enumerate(used_goods):
        out.append("\t%s = { limit = { raw_material = goods:%s }"
                   % ("if" if index == 0 else "else_if", good))
        out.append("\t\tset_global_variable = { name = wtp_realm_has_%s value = yes }" % good)
        out.append("\t}")
    out += ["}", ""]

    out += ["# Every building this mod can say something about. Scope: country",
            "wtp_collect_buildings = {"]
    for building in sorted(buildings):
        out.append("\twtp_offer_building = { b = %s }" % building)
    out += ["}", ""]

    out += ["# The methods behind one building. The runtime keeps the best of them,",
            "# which is what a building is worth in that province. Scope: country",
            ""]
    for building in sorted(buildings):
        out.append("wtp_methods_of_%s = {" % building)
        for name, _ in buildings[building]:
            out.append("\twtp_try_method = { m = %s }" % name)
        out.append("}")
    out.append("")

    for building in sorted(buildings):
        for name, method in buildings[building]:
            loc += recipe_localization(game, name, method)
    return "\n".join(out), "\n".join(loc) + "\n"


def recipe_localization(game: Game, name: str, method: Method) -> list[str]:
    """The tooltip for whichever method a building row is reporting.

    Nothing here is a word in any language — the method, the goods and the three
    captions are all `$key$` references — so one generated file serves every
    localization the mod ships.
    """
    inputs = " + ".join("%s $%s$" % (amount(value), good)
                        for good, value in sorted(method.inputs.items(),
                                                  key=lambda kv: (-kv[1], kv[0])))
    produced = "%s $%s$" % (amount(method.output), method.produced)
    local = ", ".join("$%s$" % good for good in sorted(method.raw_inputs(game.raw_goods)))
    return [' wtp_recipe_%s_desc: "$%s$\\n$WTP_IN$ %s\\n$WTP_OUT$ %s\\n$WTP_FROM_RGO$ %s"'
            % (name, method.key, inputs or "—", produced, local)]


def render_rows() -> str:
    """The switches that turn a counter into a literal row ordinal.

    Pure boilerplate, and there is a lot of it — four lists, each needing one
    switch to register itself at the right height and one to write a given row.
    `item = var:x` is pasted into the CMM macro verbatim and dies at load with
    "More than one colon in event target link", so a literal is the only way in.
    """
    out = [BOM + HEADER, "#",
           "# Scope: country for all of it.", ""]
    for setting, rows in LISTS:
        out.append("wtp_resize_%s_list = {" % setting)
        out.append("\tclear_global_variable_list = cmm_list_items_wtp__%s" % setting)
        out.append("\tif = {")
        out.append("\t\tlimit = { has_variable = cmm_list_initialized_wtp__%s }" % setting)
        out.append("\t\tremove_variable = cmm_list_initialized_wtp__%s" % setting)
        out.append("\t}")
        out.append("\tswitch = {")
        out.append("\t\ttrigger = var:wtp_%s_count" % setting)
        out.append("\t\t0 = { wtp_size_%s_list = { n = 1 } }" % setting)
        for n in range(1, rows + 1):
            out.append("\t\t%d = { wtp_size_%s_list = { n = %d } }" % (n, setting, n))
        out.append("\t}")
        out.append("}")
        out.append("")

        out.append("wtp_place_%s_row = {" % setting)
        out.append("\tswitch = {")
        out.append("\t\ttrigger = var:wtp_row_cursor")
        for n in range(1, rows + 1):
            out.append("\t\t%d = { wtp_write_%s_row = { n = %d } }" % (n, setting, n))
        out.append("\t}")
        out.append("}")
        out.append("")
    return "\n".join(out)


def check_cmm_arguments(cmf_effects: Path) -> None:
    """Warn when a cmm_ call uses an argument name CMF does not declare.

    CMF moves its own macros between files across versions — 2.4.1 split the
    list settings into three — so the declarations are read from the whole
    folder and from `scripted_guis/` beside it, never from a named file.
    """
    sources = list(cmf_effects.glob("*.txt"))
    beside = cmf_effects.parent / "scripted_guis"
    if beside.is_dir():
        sources += list(beside.glob("*.txt"))
    if not sources:
        raise SystemExit("no CMF script files under %s" % cmf_effects)
    declared = "".join(p.read_text(encoding="utf-8-sig") for p in sources)
    ours = "".join(p.read_text(encoding="utf-8-sig")
                   for folder in ("scripted_effects", "scripted_guis")
                   for p in (OUT / folder).glob("*.txt"))
    for call in re.finditer(r"(cmm_[a-z_]+) = \{([^{}]*)\}", ours):
        name, body = call.group(1), call.group(2)
        decl = re.search(r"^%s = \{(.*?)^\}" % re.escape(name), declared, re.S | re.M)
        if decl is None:
            print("unknown CMM effect: %s" % name, file=sys.stderr)
            continue
        allowed = set(re.findall(r"\$(\w+)\$", decl.group(1)))
        extra = set(re.findall(r"\b(\w+)\s*=", body)) - allowed
        if extra:
            print("%s called with %s; CMF declares %s"
                  % (name, sorted(extra), sorted(allowed)), file=sys.stderr)


def check_hand_written() -> None:
    """Warn when a row writer the generated switches call is missing."""
    effects = "".join((OUT / "scripted_effects" / n).read_text(encoding="utf-8-sig")
                      for n in ("wtp_effects.txt", "wtp_registration.txt"))
    for setting, rows in LISTS:
        for shape in ("wtp_size_%s_list = {" % setting,
                      "wtp_write_%s_row = {" % setting):
            if shape not in effects:
                print("wtp_effects.txt is missing `%s`" % shape, file=sys.stderr)


def main() -> int:
    if len(sys.argv) > 3:
        print(__doc__)
        return 2
    common = Path(sys.argv[1]) if len(sys.argv) > 1 else refs.GAME_COMMON
    missing = [n for n in ("goods", "production_methods", "building_types")
               if not (common / n).is_dir()]
    if missing:
        print("missing under %s: %s" % (common, ", ".join(missing)), file=sys.stderr)
        return 1

    game = load_game(common)
    ids = resolve_ids(game)
    gates = country_gates(common / "building_types")
    entries = load_dir(common / "building_types")
    buildings = buildings_with_methods(game, ids)
    used_goods = sorted({g for m in game.methods for g in m.raw_inputs(game.raw_goods)})

    body, loc = render_buildings(game, ids, buildings, used_goods)

    for path, text in ((TRIGGERS_OUT, render_triggers(used_goods)),
                       (AVAIL_OUT, render_availability(game, ids, gates, buildings, entries)),
                       (VALUES_OUT, render_values(game, ids)),
                       (BUILDINGS_OUT, body),
                       (ROWS_OUT, render_rows()),
                       ):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    for path in RETIRED:
        if path.exists():
            path.unlink()
            print("removed %s" % path.relative_to(MOD_ROOT.parent))

    check_cmm_arguments(Path(sys.argv[2]) if len(sys.argv) > 2
                        else refs.known("cmf") / "in_game/common/scripted_effects")
    check_hand_written()

    town = sum(1 for b in buildings if scalar(entries[b], "pop_type") in TOWN_POPS)
    print("buildings offered:        %d (%d town, %d rural)"
          % (len(buildings), town, len(buildings) - town))
    print("methods scored:           %d" % len({ids[(m.building, m.key)]
                                                for m in scored_methods(game)}))
    print("raw materials referenced: %d" % len(used_goods))
    print("most methods on one building: %d" % max(len(v) for v in buildings.values()))
    print("behind a country_potential:   %d" % sum(1 for b in buildings if b in gates))

    for language in LOC_LANGUAGES:
        path = (MOD_ROOT / "main_menu" / "localization" / language
                / ("wtp_generated_l_%s.yml" % language))
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("﻿" + loc.replace("l_english:", "l_%s:" % language, 1),
                        encoding="utf-8")

    for path in (TRIGGERS_OUT, AVAIL_OUT, VALUES_OUT, BUILDINGS_OUT, ROWS_OUT):
        print("wrote %s" % path.relative_to(MOD_ROOT.parent))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
